#ifndef IFJCODE_GENERATOR_H
#define IFJCODE_GENERATOR_H

#include "ast.h"

typedef struct Context {
    char *function_name;
    token_type return_type;
    ast_node_t *root;
    unsigned label_idx;
} context_t;


/**
 * @brief Prints string literal to stdout in IFJcode26 style
 *
 * @param string String representing the literal for print
 * @param flag True if end of line should be written on the end, false otherwise
 */
void print_string_literal(char *string, bool flag);

/**
 * @brief Discoveres the type of inputed node
 *
 * @param node Pointer to the node we want to know the type of
 * 
 * @return Type of the inputed node
 */
token_type find_operand_type (ast_node_t *node);

/**
 * @brief Generates IFJcode26 for one whole 'if' statement
 * 
 * @param node Pointer to a node that stores the contents of this 'if' statement
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_if(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for one whole 'while' statement
 * 
 * @param node Pointer to a node that stores the contents of this 'while' statement
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_while(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for one block of code
 *
 * @param node Pointer to a node that stores the start of a block
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 * @param result_needed Boolean indicating if the result of the block is needed
 */
void generate_block(ast_node_t *node, context_t *context, bool result_needed);

/**
 * @brief Generates IFJcode26 for a declaration of a variable
 *
 * @param node Pointer to a node with the variable declaration
 * @param frame String representing the frame in which the variable should be (TF, LF, GF)
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_declaration(ast_node_t *node, char *frame, context_t *context);

/**
 * @brief Generates IFJcode26 for an assignment
 * 
 * @param node Pointer to a node that stores the assignment
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_assignment(ast_node_t *node, context_t *context);

/**
 * Generated by ChatGPT, model OpenAI GPT-6
 * Prompt: Zkontroluješ chyby v mé implementaci funkce generate_definitions_in_function() a jejího použití v ostatních funkcích?
 * 
 * @brief Generates definitions of all local variables in this function to prevent multiple definitions of the same variable
 * 
 * @param node Pointer to a node representing the body of the function
 */
void generate_definitions_in_function(ast_node_t *node);

/**
 * @brief Generates IFJcode26 for a definition of a function
 *
 * @param node Pointer to a node that is holding the definition of a function
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_function(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for the 'return' statement
 * 
 * @param node Pointer to a node that stores the 'return' statement
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_return(ast_node_t *node, context_t *context);

/**
 * @brief Checks if a node represents an expression, aka. if it leaves a value on the stack
 *
 * @param node Pointer to the node strucutre to check
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 * 
 * @return true if the node represents an expression, false otherwise
 */
bool is_expression (ast_node_t *node, context_t *context);

/**
 * @brief Goes through ast and finds return type of a function with inputed name
 * 
 * @param id_val String representing the name of the searched function
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 * 
 * @return Type of the searched function
 */
token_type function_return_type(char *id_val, context_t *context);

/**
 * @brief Compares inputed name with builtin functions names
 * 
 * @param function_name String that is going to be compared to the builtin functions names
 * 
 * @return True if it matches a builtin function name, false otherwise
 */
bool is_builtin_function (char *function_name);

/**
 * @brief Generates IFJcode26 for the function call
 * 
 * @param node Pointer to the node strucutre containing the call node
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_call(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for two operands
 * 
 * @param node Pointer to a operation node strucutre containing pointers to the operands
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_operands(expr_op_node_t op_node, context_t *context);

/**
 * @brief Generates IFJcode26 for an aritmetical operation
 *
 * @param node Pointer to a node that stores the operation
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_operation(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for an identifier
 *
 * @param node Pointer to a node that stores the identifier
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_identifier(ast_node_t *node, context_t *context);

/**
 * @brief Generates IFJcode26 for any type of literal
 *
 * @param node Pointer to a node that holds the literal
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void generate_literal(ast_node_t *node, context_t *context);


/**
 * @brief Crossroad that detects the type of the node and calls functions for IFJcode26 generation
 *
 * @param node Pointer to a node
 * @param context Pointer to a structure of parameters needed by some functions in IFJcode26 generator
 */
void process_node(ast_node_t *node, context_t *context);


/**
 * @brief Implementation of built-in print(value: Any): Unit function, (instruction WRITE)
 *
 * @param node Pointer to the argument AST node
 */
void generate_print(ast_node_t *node);


/**
 * @brief Implementation of built-in readLine(): String function, reading one line from standard input, (instruction READ)
 *
 * @param target_var Pointer to a string, containing destination variable name
 */
void generate_readLine(char *target_var);


/**
 * @brief Implementation of built-in readInt(): Int function, reading an integer from standard input
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param context Pointer to a structure that is managing label names (relevant for this function)
 */
void generate_readInt(char *target_var, context_t *context);


/**
 * @brief Implementation of built-in readDouble(): Double function, reading a double from standard input
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param context Pointer to a structure that is managing label names (relevant for this function)
 */
void generate_readDouble(char *target_var, context_t *context); 


/**
 * @brief Implementation of built-in readBoolean(): Boolean function, reading a boolean from standard input
 *
 * @param target_var Pointer to a string, containing destination variable name
 */
void generate_readBoolean(char *target_var);


/**
 * @brief Implementation of built-in toStr(value: Any): String function, returns string representation of a value
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param node Pointer to the argument AST node
 */
void generate_toStr(char *target_var, ast_node_t *node);


/**
 * @brief Implementation of built-in toInt(value: Double): Int function, returns integer representation of a double, created by removing decimal part
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param node Pointer to the argument AST node
 */
void generate_toInt(char *target_var, ast_node_t *node);


/**
 * @brief Implementation of built-in strLength(value: String): Int function, returns number of characters in a string
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param node Pointer to the argument AST node
 */
void generate_strLength(char *target_var, ast_node_t *node);


/**
 * @brief Generates a call to the built-in subStr(value: String, start: Int, end: Int): String function, returns substring of value string
 *
 * @param arg1 Pointer to the first function argument
 * @param arg2 Pointer to the second function argument
 * @param arg3 Pointer to the third function argument
 */
void generate_subStr(ast_node_t *arg1, ast_node_t *arg2, ast_node_t *arg3);


/**
 * @brief Implementation of built-in subStr(value: String, start: Int, end: Int): String function in IFJcode26
 */
void generate_builtin_subStr(void);


/**
 * Generated by Google Gemini, model 4 Argon
 * Prompt: Mám to takto správne?
 * 
 * @brief Implementation of built-in ord(value: String, index: Int): Int function, returns ASCII code of a character, at a given index 
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param arg1 Pointer to the first function argument
 * @param arg2 Pointer to the second function argument
 */
void generate_ord(char *target_var, ast_node_t *arg1, ast_node_t *arg2);


/**
 * @brief Implementation of built-in chr(code: Int): String function, for a value in interval 0 to 127, returns one character string with corresponding ASCII code
 *
 * @param target_var Pointer to a string, containing destination variable name
 * @param node Pointer to the argument AST node
 */
void generate_chr(char *target_var, ast_node_t *node);

/**
 * @brief Finds the main function in ast
 * 
 * @param root Pointer to a root node of the ast
 * 
 * @return Name of the found main function
 */
char *find_main_function(ast_node_t *root);

/**
 * @brief Identifies a builtin function call and generates its corresponding IFJcode26 instructions
 * 
 * @param node Pointer to the node strucutre containing the call node
 * @param context Pointer to a structure that is managing label names (relevant for this function)
 * 
 * @return true if the builtin fuction was found and generated
 */
bool generate_builtin_call(ast_node_t *node, context_t *context);

/**
 * @brief Entry function for this module
 *
 * @param root Pointer to the root of the semantic tree that should be compiled into IFJcode26
 */
void generate_IFJcode26(ast_node_t *root);


#endif