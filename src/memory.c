void arena_init()
{
    active_arena = malloc(sizeof(arena_t));
    if(active_arena == NULL) {
        error_exit(INTERNAL_ERR, 0, "Memory allocation failed");
    }

    // Start with empty buffer at index 0
    active_arena->offset = 0;
    // End of the linked list
    active_arena->next = NULL;
}


