char *scratch_save_to_arena()
{
    // Allocate space in the arena for the string including null terminator
    char *arena_string = arena_alloc(scratch_staging_length + 1);
    memcpy(arena_string, scratch_staging_buffer, scratch_staging_length + 1);

    scratch_clear();
    return arena_string;
}


