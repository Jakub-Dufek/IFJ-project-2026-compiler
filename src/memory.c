void ast_init_arena()
{
    ast_arena = malloc(sizeof(arena_t));
    if(ast_arena == NULL) {
        error_exit(INTERNAL_ERR, 0, "Memory allocation failed");
        return;
    }

    ast_arena->offset = 0;
    ast_arena->next = NULL;
}


/* This function was generated by Gemini flash 3.8
    AND WAS MODIFIED with custom struct name
    Prompt: "Implementuj funkci init_arena pro AST" */
void ast_free_arena(void)
{
    arena_t *current = ast_arena;
    while (current != NULL) {
        arena_t *next = current->next;
        free(current);
        current = next;
    }
    ast_arena = NULL;
}


/* The lines of code within this function were generated by Gemini flash 3.8
    AND WERE MODIFIED with custom error exit function, custom names of structs and translated comments
    Prompt: "Implementuj funkci init_arena pro AST" */
void *ast_alloc(unsigned size)
{
   size = align_size(size);

    if(ast_arena == NULL) {
        ast_init_arena();
        if(ast_arena == NULL) {
            return NULL;
        }
    }

    // Allocation of next arena in case first block of data gets filled up 
    if(ast_arena->offset + size > ARENA_SIZE) {
        arena_t *new_arena = malloc(sizeof(arena_t));
        if(new_arena == NULL) {
            error_exit(INTERNAL_ERR, 0, "Memory allocation failed");
            return NULL;
        }

        new_arena->offset = 0;
        new_arena->next = ast_arena; // Block intertwining
        ast_arena = new_arena;
    }

    void *ptr = &ast_arena->arena[ast_arena->offset];
    ast_arena->offset += (int)size;

    return ptr;
}



