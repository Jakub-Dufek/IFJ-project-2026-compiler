void scratch_append(char character)
{
    // Ensure space for the new character plus the terminating '\0'
    if(scratch_staging_length + 2 > scratch_staging_capacity) {
        scratch_staging_capacity *= 2;

        scratch_staging_buffer = realloc(scratch_staging_buffer, scratch_staging_capacity);
        if(scratch_staging_buffer == NULL) {
            error_exit(INTERNAL_ERR, 0, "Memory allocation failed");
        }
    }

    scratch_staging_buffer[scratch_staging_length] = character;
    scratch_staging_length++;
    scratch_staging_buffer[scratch_staging_length] = '\0';
}


