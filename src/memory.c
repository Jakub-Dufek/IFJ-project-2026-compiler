/// Arena for strings and AST nodes
static arena_t *active_arena = NULL;

/// Temporary staging buffer for building scanner strings
static char *scratch_staging_buffer = NULL;
static unsigned scratch_staging_length = 0;
static unsigned scratch_staging_capacity = 0;



