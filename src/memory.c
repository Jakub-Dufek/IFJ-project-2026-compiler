/**
 * @brief Aligns size in arena for 8-byte memory
 *
 * @param size original size in bytes
 *
 * @return aligned size in bytes
 *
 * This function was generated by Gemini flash 3.8
 * Prompt: "Implementuj funkci init_arena pro AST"
 */
static unsigned align_size(unsigned size)
{
    const unsigned alignment = alignof(max_align_t);
    // aligns up to 8 bytes so any struct can be safely stored
    return (size + alignment - 1) & ~(alignment - 1);
}



