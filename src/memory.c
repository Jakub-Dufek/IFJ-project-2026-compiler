void *arena_alloc(unsigned size)
{
    size = align_size(size);
    if(size > ARENA_SIZE) {
        error_exit(INTERNAL_ERR, 0, "Requested allocation size exceeds maximum arena block size");
    }

    // if requested size does not fit, allocate new block
    if(active_arena->offset + size > ARENA_SIZE) {
        arena_t *new_block = malloc(sizeof(arena_t));
        if(new_block == NULL) {
            error_exit(INTERNAL_ERR, 0, "Memory allocation failed");
        }

        new_block->offset = 0;
        new_block->next = active_arena;
        active_arena = new_block;
    }

    // get pointer to first free byte in new active block
    void *allocated_memory = &active_arena->arena[active_arena->offset];

    active_arena->offset += size;
    return allocated_memory;
}


